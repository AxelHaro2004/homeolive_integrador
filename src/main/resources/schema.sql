CREATE TABLE categoria_producto (
                                    id_categoria      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    nombre_categoria  VARCHAR(100) NOT NULL,
                                    activo            BOOLEAN DEFAULT TRUE NOT NULL,               -- [+] eliminación lógica
                                    CONSTRAINT uq_categoria_nombre UNIQUE (nombre_categoria),
                                    CONSTRAINT ck_categoria_nombre CHECK (CHAR_LENGTH(TRIM(nombre_categoria)) > 0)
);


CREATE TABLE producto (
                          id_producto      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre_producto  VARCHAR(100) NOT NULL,
                          CONSTRAINT uq_producto_nombre UNIQUE (nombre_producto)
);

CREATE TABLE categoria_presentacion (
                                        id_presentacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        id_categoria     INT NOT NULL,
                                        presentacion     INT NOT NULL,
                                        unidad_medida    VARCHAR(10) NOT NULL,
                                        precio_unitario  DECIMAL(10,2) NOT NULL,
                                        activo           BOOLEAN DEFAULT TRUE NOT NULL,                -- [+] eliminación lógica
                                        CONSTRAINT fk_presentacion_categoria FOREIGN KEY (id_categoria) REFERENCES categoria_producto (id_categoria),
                                        CONSTRAINT uq_presentacion UNIQUE (id_categoria, presentacion, unidad_medida),
                                        CONSTRAINT ck_presentacion_valor CHECK (presentacion > 0),
                                        CONSTRAINT ck_presentacion_unidad CHECK (unidad_medida IN ('ml', 'gr', 'cápsulas')),
                                        CONSTRAINT ck_presentacion_precio CHECK (precio_unitario >= 0)
);

CREATE TABLE medicina_talonario (
                                    id_medicina_talonario  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    id_producto            INT NOT NULL,
                                    id_presentacion        INT NOT NULL,
                                    CONSTRAINT fk_talonario_producto FOREIGN KEY (id_producto) REFERENCES producto (id_producto),
                                    CONSTRAINT fk_talonario_presentacion FOREIGN KEY (id_presentacion) REFERENCES categoria_presentacion (id_presentacion),
                                    CONSTRAINT uq_talonario UNIQUE (id_producto, id_presentacion)
);

CREATE TABLE cliente (
                         id_cliente        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombre_cliente    VARCHAR(100) NOT NULL,
                         telefono_cliente  VARCHAR(13)  NOT NULL,
                         dni_cliente       VARCHAR(11)  NOT NULL,
                         ubicacion         VARCHAR(10)  NOT NULL,                       -- [+] Lima / Provincia
                         CONSTRAINT uq_cliente_dni UNIQUE (dni_cliente),
                         CONSTRAINT ck_cliente_ubicacion CHECK (ubicacion IN ('Lima', 'Provincia'))
);

CREATE TABLE pedido_verificado (
                                   id_pedido            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   codigo_pedido        VARCHAR(12)   NOT NULL,                   -- [+] N° de pedido (PED-1049)
                                   codigo_venta         VARCHAR(12)   NOT NULL,                   -- [+] N° de venta (VEN-5082)
                                   id_cliente           INT           NOT NULL,
                                   fecha_verificacion   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
                                   fecha_actualizacion  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,   -- [+] último cambio de estado
                                   monto_pago           DECIMAL(10,2) NOT NULL,
                                   ubicacion_entrega    VARCHAR(10)   NOT NULL,                   -- [+] Lima / Provincia
                                   tipo_envio           VARCHAR(12)   NOT NULL,                   -- [+] MOTORIZADO / OLVA / SHALOM
                                   estado               VARCHAR(50)   DEFAULT 'EN_PREPARACION' NOT NULL,
                                   CONSTRAINT uq_pedido_codigo UNIQUE (codigo_pedido),
                                   CONSTRAINT uq_pedido_venta UNIQUE (codigo_venta),
                                   CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
                                   CONSTRAINT ck_pedido_monto CHECK (monto_pago >= 0),
                                   CONSTRAINT ck_pedido_ubicacion CHECK (ubicacion_entrega IN ('Lima', 'Provincia')),
                                   CONSTRAINT ck_pedido_envio CHECK (tipo_envio IN ('MOTORIZADO', 'OLVA', 'SHALOM')),
                                   CONSTRAINT ck_pedido_provincia_courier CHECK (NOT (ubicacion_entrega = 'Provincia' AND tipo_envio = 'MOTORIZADO')),
                                   CONSTRAINT ck_pedido_estado CHECK (estado IN ('EN_PREPARACION', 'LISTO_PARA_ENVIO', 'POR_CONFIRMAR', 'ENTREGADO'))
);
CREATE INDEX idx_pedido_cliente ON pedido_verificado (id_cliente);
CREATE INDEX idx_pedido_estado ON pedido_verificado (estado);
CREATE INDEX idx_pedido_fecha ON pedido_verificado (fecha_verificacion);

CREATE TABLE detalle_pedido (
                                id_detalle_pedido      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                id_pedido              INT NOT NULL,
                                id_medicina_talonario  INT NOT NULL,
                                cantidad               INT NOT NULL,
                                precio_unitario_venta  DECIMAL(10,2) NOT NULL,
                                CONSTRAINT fk_detalle_pedido FOREIGN KEY (id_pedido) REFERENCES pedido_verificado (id_pedido) ON DELETE CASCADE,
                                CONSTRAINT fk_detalle_talonario FOREIGN KEY (id_medicina_talonario) REFERENCES medicina_talonario (id_medicina_talonario),
                                CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
                                CONSTRAINT ck_detalle_precio CHECK (precio_unitario_venta >= 0)
);
CREATE INDEX idx_detalle_pedido ON detalle_pedido (id_pedido);

CREATE TABLE empleado (
                          id_empleado        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre_empleado    VARCHAR(100) NOT NULL,
                          dni_empleado       VARCHAR(11)  NOT NULL,
                          cargo              VARCHAR(25)  NOT NULL,
                          telefono_empleado  VARCHAR(15),
                          CONSTRAINT uq_empleado_dni UNIQUE (dni_empleado),
                          CONSTRAINT uq_empleado_telefono UNIQUE (telefono_empleado),
                          CONSTRAINT ck_empleado_cargo CHECK (cargo IN ('administracion', 'vendedor', 'quimico_farmaceutico', 'gestor_envios', 'agente_finanzas'))
);

CREATE TABLE usuario (
                         id_usuario   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         username     VARCHAR(50)  NOT NULL,
                         password     VARCHAR(255) NOT NULL,
                         rol_sistema  VARCHAR(30)  NOT NULL,
                         correo_user  VARCHAR(200) NOT NULL,
                         id_empleado  INT          NOT NULL,
                         CONSTRAINT uq_usuario_username UNIQUE (username),
                         CONSTRAINT uq_usuario_correo UNIQUE (correo_user),
                         CONSTRAINT uq_usuario_empleado UNIQUE (id_empleado),
                         CONSTRAINT fk_usuario_empleado FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado),
                         CONSTRAINT ck_usuario_rol CHECK (rol_sistema IN ('administrador', 'vendedor', 'quimico_farmaceutico', 'gestor_envios', 'agente_finanzas'))
);

CREATE TABLE empaquetado (
                             id_empaquetado     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             fecha_empaquetado  TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
                             courier            VARCHAR(12) NOT NULL,
                             id_pedido_courier  VARCHAR(50),
                             id_empleado        INT NOT NULL,
                             id_pedido          INT NOT NULL,
                             CONSTRAINT fk_empaquetado_empleado FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado),
                             CONSTRAINT fk_empaquetado_pedido FOREIGN KEY (id_pedido) REFERENCES pedido_verificado (id_pedido) ON DELETE CASCADE,
                             CONSTRAINT ck_empaquetado_courier CHECK (courier IN ('OLVA', 'SHALOM', 'MOTORIZADO')),
                             CONSTRAINT ck_empaquetado_id_courier CHECK (courier = 'MOTORIZADO' OR id_pedido_courier IS NOT NULL)
);
CREATE INDEX idx_empaquetado_pedido ON empaquetado (id_pedido);

CREATE TABLE insumo_empaquetado (
                                    id_insumo_empaquetado  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    nombre                 VARCHAR(100)  NOT NULL,
                                    stock                  DECIMAL(10,2) NOT NULL,
                                    unidad                 VARCHAR(10)   NOT NULL,
                                    CONSTRAINT uq_insumo_nombre UNIQUE (nombre),
                                    CONSTRAINT ck_insumo_stock CHECK (stock >= 0)
);

CREATE TABLE empaquetado_consume (
                                     id_empaquetado_consume  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     id_empaquetado          INT NOT NULL,
                                     id_insumo_empaquetado   INT NOT NULL,
                                     cantidad                DECIMAL(10,2) NOT NULL,
                                     CONSTRAINT fk_consume_empaquetado FOREIGN KEY (id_empaquetado) REFERENCES empaquetado (id_empaquetado) ON DELETE CASCADE,
                                     CONSTRAINT fk_consume_insumo FOREIGN KEY (id_insumo_empaquetado) REFERENCES insumo_empaquetado (id_insumo_empaquetado),
                                     CONSTRAINT ck_consume_cantidad CHECK (cantidad > 0)
);
